"""Генерация UML-диаграмм деятельности (Graphviz DOT) для PortaGraph.

Нотация: ● начальный узел; ◉ конечный узел; скруглённый прямоугольник — действие;
ромб — узел решения/слияния (условия в квадратных скобках на рёбрах);
жирная черта — разветвление/соединение параллельных потоков.
"""
import subprocess, textwrap

HEAD = """digraph AD {
  graph [rankdir=TB, fontname="DejaVu Sans", fontsize=13, nodesep=0.35, ranksep=0.32, pad=0.3, splines=ortho, labelloc=t, forcelabels=true];
  node  [fontname="DejaVu Sans", fontsize=11, shape=box, style="rounded,filled", fillcolor="#eef3fb", color="#2f4ac0", penwidth=1.3, margin="0.14,0.06"];
  edge  [fontname="DejaVu Sans", fontsize=10, color="#333333", arrowhead=vee, arrowsize=0.8];
"""

def wrap(t, w=34):
    return "\\n".join(textwrap.wrap(t, w)) if "\\n" not in t else t

def build(name, title, spec):
    out = [HEAD, f'  label="{title}\\n\\n"; fontsize=14;']
    for nid, kind, text in spec["nodes"]:
        if kind == "start":
            out.append(f'  {nid} [shape=circle, style=filled, fillcolor=black, label="", width=0.26, fixedsize=true, color=black];')
        elif kind == "end":
            out.append(f'  {nid} [shape=circle, peripheries=2, style=filled, fillcolor=black, color=black, label="", width=0.26, fixedsize=true];')
        elif kind == "dec":
            out.append(f'  {nid} [shape=diamond, style=filled, fillcolor="#ffffff", color="#333333", label="", width=0.36, height=0.36, fixedsize=true];')
        elif kind == "bar":
            out.append(f'  {nid} [shape=box, style=filled, fillcolor=black, color=black, label="", width=2.8, height=0.06, fixedsize=true];')
        elif kind == "note":
            out.append(f'  {nid} [shape=note, style=filled, fillcolor="#fff9db", color="#888888", fontsize=10, label="{wrap(text, 30)}"];')
        elif kind == "uniq":
            out.append(f'  {nid} [label="{wrap(text)}", fillcolor="#ffe8a3", color="#d9480f", penwidth=1.8];')
        else:
            out.append(f'  {nid} [label="{wrap(text)}"];')
    for e in spec["edges"]:
        a, b = e[0], e[1]
        attrs = []
        if len(e) > 2 and e[2]:
            attrs.append(f'xlabel=" {e[2]} "')
        if len(e) > 3:
            attrs.append(e[3])
        out.append(f'  {a} -> {b} [{", ".join(attrs)}];')
    for r in []:
        out.append("  { rank=same; " + "; ".join(r) + "; }")
    out.append("}")
    src = f"{name}.dot"
    open(src, "w").write("\n".join(out))
    subprocess.run(["dot", "-Tpng", "-Gdpi=150", src, "-o", f"../{name}.png"], check=True)


